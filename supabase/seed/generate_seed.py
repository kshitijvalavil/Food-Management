#!/usr/bin/env python3
"""Generate supabase/seed.sql from supabase/seed/curated_foods.csv.

Usage:  python3 -I supabase/seed/generate_seed.py
Stdlib only. Validates every row and fails loudly instead of writing a bad seed.
See supabase/seed/README.md for where the data comes from (and the FoodKeeper TODO).
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CSV_PATH = HERE / "curated_foods.csv"
OUT_PATH = HERE.parent / "seed.sql"

LOCATIONS = {"fridge", "freezer", "pantry"}
DAY_COLS = [
    "pantry_min", "pantry_max", "fridge_min", "fridge_max", "freezer_min", "freezer_max",
]
SOURCE = "curated"  # not 'foodkeeper': these rows are hand-authored, not USDA data


def sql_text(value: str | None) -> str:
    if value is None or value == "":
        return "null"
    return "'" + value.replace("'", "''") + "'"


def sql_int(value: str) -> str:
    return "null" if value == "" else str(int(value))


def sql_text_array(values: list[str]) -> str:
    return "array[" + ", ".join(sql_text(v) for v in values) + "]::text[]"


def validate(row: dict[str, str], seen_ids: set[int], seen_names: set[str]) -> list[str]:
    errs: list[str] = []
    rid = int(row["id"])
    if rid in seen_ids:
        errs.append(f"duplicate id {rid}")
    seen_ids.add(rid)
    key = row["name"].strip().lower()
    if key in seen_names:
        errs.append(f"duplicate name {row['name']!r}")
    seen_names.add(key)
    loc = row["default_location"]
    if loc not in LOCATIONS:
        errs.append(f"bad default_location {loc!r}")
    for col in DAY_COLS:
        if row[col] != "" and int(row[col]) < 0:
            errs.append(f"{col} is negative")
    for place in ("pantry", "fridge", "freezer"):
        lo, hi = row[f"{place}_min"], row[f"{place}_max"]
        if (lo == "") != (hi == ""):
            errs.append(f"{place}: set both min and max or neither")
        elif lo != "" and int(lo) > int(hi):
            errs.append(f"{place}: min > max")
    if loc in LOCATIONS and row[f"{loc}_max"] == "":
        errs.append(f"default_location {loc} has no days")
    kws = [k.strip() for k in row["keywords"].split("|") if k.strip()]
    if not kws:
        errs.append("no keywords")
    for k in kws:
        if k != k.lower():
            errs.append(f"keyword {k!r} must be lowercase")
    return [f"row id={row['id']} ({row['name']}): {e}" for e in errs]


def main() -> int:
    with CSV_PATH.open(newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))

    errors: list[str] = []
    seen_ids: set[int] = set()
    seen_names: set[str] = set()
    for row in rows:
        errors += validate(row, seen_ids, seen_names)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1

    lines = [
        "-- GENERATED by supabase/seed/generate_seed.py from supabase/seed/curated_foods.csv. Do not edit by hand.",
        "-- source='curated': hand-authored placeholder data, NOT USDA FoodKeeper.",
        "-- TODO: replace with FoodKeeper rows (source='foodkeeper') once www.fsis.usda.gov is reachable; see supabase/seed/README.md.",
        "",
        "insert into public.shelf_life (",
        "  id, name, category, keywords, default_location,",
        "  pantry_min_days, pantry_max_days, fridge_min_days, fridge_max_days, freezer_min_days, freezer_max_days,",
        "  tips, source",
        ") values",
    ]
    values = []
    for row in rows:
        kws = [k.strip() for k in row["keywords"].split("|") if k.strip()]
        values.append(
            "  ("
            + ", ".join(
                [
                    str(int(row["id"])),
                    sql_text(row["name"].strip()),
                    sql_text(row["category"].strip()),
                    sql_text_array(kws),
                    sql_text(row["default_location"]) + "::public.location",
                    *[sql_int(row[c]) for c in DAY_COLS],
                    sql_text(row["tips"].strip() or None),
                    sql_text(SOURCE),
                ]
            )
            + ")"
        )
    lines.append(",\n".join(values))
    lines += [
        "on conflict (id) do update set",
        "  name = excluded.name, category = excluded.category, keywords = excluded.keywords,",
        "  default_location = excluded.default_location,",
        "  pantry_min_days = excluded.pantry_min_days, pantry_max_days = excluded.pantry_max_days,",
        "  fridge_min_days = excluded.fridge_min_days, fridge_max_days = excluded.fridge_max_days,",
        "  freezer_min_days = excluded.freezer_min_days, freezer_max_days = excluded.freezer_max_days,",
        "  tips = excluded.tips, source = excluded.source;",
        "",
    ]
    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(rows)} shelf_life rows to {OUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
